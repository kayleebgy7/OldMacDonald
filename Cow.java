package OldMacDonald;
public class Cow extends Animal {
    private String type;
    private String sound;

    public Cow(String type, String sound) {
        this.type = type;
        this.sound = sound;
    }

    public String getSound() 
    {
    
       return sound;
    }
    public String getType() {
    
        return type;
   
    }
   
}

    

